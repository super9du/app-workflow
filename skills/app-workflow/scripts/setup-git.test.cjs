// 仅在临时目录验证仓库初始化，不触碰当前项目或全局配置。
const { test, after } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'app-workflow-git-'))
after(() => fs.rmSync(root, { recursive: true, force: true }))
function fixture(name) { const dir = path.join(root, name); fs.mkdirSync(dir); return dir }
function run(dir, env = process.env) {
  return spawnSync(process.execPath, [path.join(__dirname, 'setup-git.cjs'), dir], { encoding: 'utf8', env })
}
test('未初始化项目创建仓库，重复运行保留配置，子目录复用父仓库', () => {
  const dir = fixture('project')
  assert.equal(run(dir).status, 0)
  assert.ok(fs.existsSync(path.join(dir, '.git', 'HEAD')))
  const config = path.join(dir, '.git', 'config')
  const before = fs.readFileSync(config, 'utf8')
  assert.equal(run(dir).status, 0)
  assert.equal(fs.readFileSync(config, 'utf8'), before)
  const child = path.join(dir, 'child'); fs.mkdirSync(child)
  assert.equal(run(child).status, 0)
  assert.equal(fs.existsSync(path.join(child, '.git')), false)
})
test('缺少 Git 时返回安装提示且不创建仓库', () => {
  const dir = fixture('missing-git')
  const result = run(dir, { ...process.env, PATH: dir })
  assert.equal(result.status, 2)
  assert.match(result.stderr, /git-scm.com/)
  assert.equal(fs.existsSync(path.join(dir, '.git')), false)
})
test('已有损坏的仓库不被重新初始化', () => {
  const dir = fixture('broken')
  fs.writeFileSync(path.join(dir, '.git'), 'gitdir: missing\n')
  assert.equal(run(dir).status, 1)
  assert.equal(fs.readFileSync(path.join(dir, '.git'), 'utf8'), 'gitdir: missing\n')
})
test('worktree 复用已有 Git 元数据', () => {
  const dir = fixture('source')
  assert.equal(run(dir).status, 0)
  const commit = spawnSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false', 'commit', '--allow-empty', '-m', '测试基线'], { cwd: dir, encoding: 'utf8' })
  assert.equal(commit.status, 0, commit.stderr)
  const target = path.join(root, 'worktree')
  const added = spawnSync('git', ['worktree', 'add', '--detach', target], { cwd: dir, encoding: 'utf8' })
  assert.equal(added.status, 0, added.stderr)
  const before = fs.readFileSync(path.join(target, '.git'), 'utf8')
  assert.equal(run(target).status, 0)
  assert.equal(fs.readFileSync(path.join(target, '.git'), 'utf8'), before)
})
test('无效路径失败，不创建项目目录', () => {
  const dir = path.join(root, 'absent')
  assert.equal(run(dir).status, 1)
  assert.equal(fs.existsSync(dir), false)
})
